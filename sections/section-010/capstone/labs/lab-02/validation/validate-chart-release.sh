#!/usr/bin/env bash
# Check both the saved chart and live release, then send a request from shuttle.
set -euo pipefail
export PATH="$HOME/.astrona/bin:$PATH"
fail() { echo "FAIL: chart-release: $*"; exit 1; }
CHART_DIR="$HOME/resources/scout"
VALUES_FILE="$HOME/resources/production-values.yaml"
[[ -f "$CHART_DIR/Chart.yaml" && -f "$VALUES_FILE" ]] || fail "save the chart and production-values.yaml in ~/resources"
CHART_METADATA="$(helm show chart "$CHART_DIR")" || fail "cannot read chart"
grep -qx 'version: 0.2.0' <<<"$CHART_METADATA" || fail "chart version must be 0.2.0"
grep -Eq '^appVersion: "?6\.15\.0"?$' <<<"$CHART_METADATA" || fail "appVersion must be 6.15.0"
grep -Eq '\.Values\.message' "$CHART_DIR/templates/deployment.yaml" || fail "the Deployment template must read .Values.message"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
for FILE in values.yaml templates/service.yaml; do
  cmp -s "$CHART_DIR/$FILE" "$SCRIPT_DIR/../resources/scout/$FILE" || fail "keep the starter $FILE unchanged; use the override file"
done
helm lint "$CHART_DIR" -f "$VALUES_FILE" >/dev/null || fail "chart lint failed"
LOCAL_MANIFEST="$(helm template scout "$CHART_DIR" -n starfleet-production -f "$VALUES_FILE")" || fail "chart rendering failed"
RELEASE_MANIFEST="$(helm get manifest scout -n starfleet-production)" || fail "install the scout release"
[[ "$LOCAL_MANIFEST" == "$RELEASE_MANIFEST" ]] || fail "saved chart and values differ from the installed release"
RELEASE="$(helm list -n starfleet-production --filter '^scout$' -o json)" || fail "cannot list releases"
grep -Eq '"chart"[[:space:]]*:[[:space:]]*"scout-0.2.0"' <<<"$RELEASE" || fail "deployed chart must be scout-0.2.0"
grep -Eq '"app_version"[[:space:]]*:[[:space:]]*"6.15.0"' <<<"$RELEASE" || fail "release appVersion must be 6.15.0"
grep -Eq '"status"[[:space:]]*:[[:space:]]*"deployed"' <<<"$RELEASE" || fail "release is not deployed"
IMAGE="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.spec.template.spec.containers[0].image}')" || fail "no scout Deployment"
[[ "$IMAGE" == ghcr.io/stefanprodan/podinfo:6.15.0 ]] || fail "wrong scout image"
PROBE="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.spec.template.spec.containers[0].readinessProbe.httpGet.path}')"
[[ "$PROBE" == /readyz ]] || fail "keep the starter readiness probe"
SELECTOR="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.spec.selector.matchLabels.app\.kubernetes\.io/instance}')"
LABEL="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.spec.template.metadata.labels.app\.kubernetes\.io/instance}')"
[[ "$SELECTOR" == scout && "$LABEL" == scout ]] || fail "keep the release labels and selector"
REPLICAS="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.spec.replicas}')"
READY="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.status.readyReplicas}')"
[[ "$REPLICAS" == 2 && "$READY" == 2 ]] || fail "need 2 ready replicas"
MESSAGE="$(kubectl -n starfleet-production get deploy scout -o jsonpath='{.spec.template.spec.containers[0].env[?(@.name=="PODINFO_UI_MESSAGE")].value}')"
[[ "$MESSAGE" == chart-production ]] || fail "set PODINFO_UI_MESSAGE through the template and values"
BODY="$(kubectl -n starfleet exec deploy/shuttle -- curl -fsS --max-time 10 http://scout.starfleet-production/)" || fail "request from shuttle failed"
grep -Eq '"version": *"6.15.0"' <<<"$BODY" || fail "response version differs"
grep -Eq '"message": *"chart-production"' <<<"$BODY" || fail "response message differs"
echo "PASS: chart-release"
